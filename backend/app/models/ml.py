from datetime import datetime
from sqlalchemy import (
    Column, Integer, String, Float, Boolean, DateTime, Text, ForeignKey, JSON
)
from sqlalchemy.orm import relationship
from app.core.database import Base
from app.core.datetime_utils import get_utc_now


class ModelVersion(Base):
    """Registry of trained machine learning model artifacts and hyperparameters."""
    __tablename__ = "model_versions"

    id = Column(Integer, primary_key=True, index=True)
    model_name = Column(String(100), nullable=False)  # e.g., 'CIT_RF_Expected_v1', 'CIT_LSTM_v1'
    algorithm = Column(String(50), nullable=False)    # 'RandomForestRegressor', 'IsolationForest', 'LSTM'
    version_tag = Column(String(50), nullable=False, unique=True, index=True)
    file_path = Column(String(255), nullable=False)
    hyperparameters = Column(JSON, nullable=True)     # Dictionary of params (e.g. n_estimators, max_depth)
    metrics = Column(JSON, nullable=True)             # Train/validation metrics (MAE, RMSE, R2)
    is_active = Column(Boolean, default=True, nullable=False)
    notes = Column(Text, nullable=True)
    trained_at = Column(DateTime, default=get_utc_now, nullable=False)

    # Relationships
    predictions = relationship("Prediction", back_populates="model_version")
    evaluation_runs = relationship("ModelEvaluationRun", back_populates="model_version", cascade="all, delete-orphan")

    def __repr__(self):
        return f"<ModelVersion(id={self.id}, tag='{self.version_tag}', algo='{self.algorithm}', active={self.is_active})>"


class Prediction(Base):
    """Expected energy consumption inferences generated by ML models."""
    __tablename__ = "predictions"

    id = Column(Integer, primary_key=True, index=True)
    reading_id = Column(Integer, ForeignKey("energy_readings.id", ondelete="CASCADE"), nullable=False, index=True)
    building_id = Column(Integer, ForeignKey("buildings.id", ondelete="CASCADE"), nullable=False, index=True)
    model_version_id = Column(Integer, ForeignKey("model_versions.id", ondelete="SET NULL"), nullable=True, index=True)

    predicted_energy_kwh = Column(Float, nullable=False)
    residual_kwh = Column(Float, nullable=False)         # Actual - Predicted
    deviation_pct = Column(Float, nullable=True)         # (Residual / Predicted) * 100
    created_at = Column(DateTime, default=get_utc_now, nullable=False)

    # Relationships
    reading = relationship("EnergyReading", back_populates="predictions")
    building = relationship("Building", back_populates="predictions")
    model_version = relationship("ModelVersion", back_populates="predictions")
    anomaly_events = relationship("AnomalyEvent", back_populates="prediction")

    def __repr__(self):
        return f"<Prediction(id={self.id}, reading_id={self.reading_id}, pred_kWh={self.predicted_energy_kwh}, res={self.residual_kwh})>"


class ModelEvaluationRun(Base):
    """Model evaluation metadata and benchmark metrics (MAE, RMSE, R²)."""
    __tablename__ = "model_evaluation_runs"

    id = Column(Integer, primary_key=True, index=True)
    model_version_id = Column(Integer, ForeignKey("model_versions.id", ondelete="CASCADE"), nullable=False, index=True)
    dataset_name = Column(String(100), nullable=False)
    test_period_start = Column(DateTime, nullable=False)
    test_period_end = Column(DateTime, nullable=False)
    sample_count = Column(Integer, nullable=False)
    
    # Core Metrics
    mae = Column(Float, nullable=False)   # Mean Absolute Error (kWh)
    rmse = Column(Float, nullable=False)  # Root Mean Squared Error (kWh)
    r2_score = Column(Float, nullable=False) # Coefficient of Determination
    
    notes = Column(Text, nullable=True)
    created_at = Column(DateTime, default=get_utc_now, nullable=False)

    # Relationship
    model_version = relationship("ModelVersion", back_populates="evaluation_runs")

    def __repr__(self):
        return f"<ModelEvaluationRun(id={self.id}, model_id={self.model_version_id}, R2={self.r2_score:.3f}, MAE={self.mae:.2f})>"

